"""Generate YASB's dark CSS palette from a wallpaper; preview unless --apply."""

import argparse
import colorsys
import os
from pathlib import Path
import tempfile

import colorgram
from PIL import Image


OUTPUT = Path(__file__).resolve().parents[1] / "css" / "root.css"


def mix(first, second, amount):
    return tuple(round(a * (1 - amount) + b * amount) for a, b in zip(first, second))


def tone(rgb, saturation, lightness):
    hue, _, source_saturation = colorsys.rgb_to_hls(*(value / 255 for value in rgb))
    saturation = min(saturation, source_saturation)
    return tuple(round(value * 255) for value in colorsys.hls_to_rgb(hue, lightness, saturation))


def luminance(rgb):
    values = [v / 255 for v in rgb]
    linear = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in values]
    return sum(v * weight for v, weight in zip(linear, (0.2126, 0.7152, 0.0722)))


def contrast(first, second):
    light, dark = sorted((luminance(first), luminance(second)), reverse=True)
    return (light + 0.05) / (dark + 0.05)


def foreground(background):
    return max(((20, 20, 20), (255, 255, 255)), key=lambda c: contrast(c, background))


def readable(color, background):
    for _ in range(32):
        if contrast(color, background) >= 4.5:
            return color
        color = mix(color, (255, 255, 255), 0.1)
    return (255, 255, 255)


def build_palette(colors):
    dominant = colors[0][0]
    accent_source = max(colors, key=lambda item: item[1] ** 0.5 *
                        colorsys.rgb_to_hls(*(v / 255 for v in item[0]))[2])[0]
    background = tone(dominant, 0.12, 0.16)
    surface = tone(dominant, 0.10, 0.12)
    primary = tone(dominant, 0.12, 0.94)
    secondary = readable(tone(dominant, 0.10, 0.64), background)
    accent = readable(tone(accent_source, 0.65, 0.68), background)
    badge = tone(colors[1][0] if len(colors) > 1 else dominant, 0.35, 0.78)
    return {
        "bar-background": background,
        "bar-border": mix(background, primary, 0.16),
        "media-background": surface,
        "text-primary": primary,
        "text-secondary": secondary,
        "text-controls": mix(primary, secondary, 0.2),
        "text-disabled": mix(secondary, surface, 0.45),
        "accent": accent,
        "accent-hover": mix(accent, (255, 255, 255), 0.18),
        "on-accent": foreground(accent),
        "badge-background": badge,
        "badge-text": foreground(badge),
    }


def render(palette):
    lines = ["/* Generated by scripts/wallpaper_theme.py. */", ":root {"]
    for name, rgb in palette.items():
        lines.append(f"    --{name}: #{''.join(f'{v:02x}' for v in rgb)};")
    return "\n".join([*lines, "}", ""])


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
        os.replace(temporary, path)
        # YASB watches modifications, not atomic replacements.
        os.utime(path, None)
    finally:
        Path(temporary).unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", type=Path)
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    try:
        with Image.open(args.image) as image:
            image.thumbnail((160, 160))
            colors = colorgram.extract(image, 12)
        if not colors:
            raise ValueError("La imagen no contiene colores visibles")
        colors = sorted(((color.rgb, color.proportion) for color in colors),
                        key=lambda item: item[1], reverse=True)
        css = render(build_palette(colors))
        if args.apply:
            # shortcut: overlapping runs finish in any order; add a worker queue if needed.
            if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8-sig") != css:
                atomic_write(OUTPUT, css)
            else:
                os.utime(OUTPUT, None)
            print(f"Actualizado: {OUTPUT}")
        else:
            print(css, end="")
    except (OSError, ValueError) as error:
        parser.exit(1, f"No se pudo aplicar el tema: {error}\n")


if __name__ == "__main__":
    main()
